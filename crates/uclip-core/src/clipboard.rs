//! Clipboard access behind one small trait. The engine polls `token()` (cheap) and only calls
//! `read()` when it changed. Each backend lives on a single dedicated thread, so it does not
//! have to be `Send`.

use crate::wire::{ClipItem, MAX_TEXT};
use anyhow::{Result, bail};
use std::path::PathBuf;

pub trait Clipboard {
    /// Changes whenever the clipboard content changes (macOS: the pasteboard change count).
    fn token(&self) -> u64;
    /// Current content, or `None` if empty, unsupported, or marked secret by a password manager.
    fn read(&self) -> Option<ClipItem>;
    fn write(&self, item: &ClipItem) -> Result<()>;
}

pub type Factory = Box<dyn FnOnce() -> Box<dyn Clipboard> + Send>;

/// `file:/path` gives a clipboard backed by a text file (used by tests and demos).
/// `None` gives the system clipboard.
pub fn from_spec(spec: Option<&str>) -> Result<Factory> {
    match spec {
        Some(s) if s.starts_with("file:") => {
            let path = PathBuf::from(&s[5..]);
            Ok(Box::new(move || Box::new(FileClipboard { path })))
        }
        Some(other) => bail!("unknown clipboard spec {other:?}"),
        None => system(),
    }
}

#[cfg(target_os = "macos")]
fn system() -> Result<Factory> {
    Ok(Box::new(|| Box::new(mac::MacClipboard)))
}

#[cfg(target_os = "linux")]
fn system() -> Result<Factory> {
    Ok(Box::new(|| Box::new(linux::LinuxClipboard::new())))
}

#[cfg(not(any(target_os = "macos", target_os = "linux")))]
fn system() -> Result<Factory> {
    bail!("the system clipboard is not implemented on this platform yet; use UCLIP_CLIPBOARD=file:/path")
}

pub struct FileClipboard {
    pub path: PathBuf,
}

impl Clipboard for FileClipboard {
    fn token(&self) -> u64 {
        std::fs::metadata(&self.path)
            .and_then(|m| m.modified())
            .ok()
            .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
            .map(|d| d.as_nanos() as u64)
            .unwrap_or(0)
    }

    fn read(&self) -> Option<ClipItem> {
        let text = std::fs::read_to_string(&self.path).ok()?;
        (!text.is_empty() && text.len() <= MAX_TEXT).then_some(ClipItem::Text(text))
    }

    fn write(&self, item: &ClipItem) -> Result<()> {
        let ClipItem::Text(t) = item;
        std::fs::write(&self.path, t)?;
        Ok(())
    }
}

#[cfg(target_os = "macos")]
mod mac {
    use super::*;
    use objc2::rc::autoreleasepool;
    use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};
    use objc2_foundation::NSString;

    /// Items that password managers and apps mark as secret or machine-made. Never synced.
    const SKIP: [&str; 3] = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

    pub struct MacClipboard;

    impl Clipboard for MacClipboard {
        fn token(&self) -> u64 {
            autoreleasepool(|_| NSPasteboard::generalPasteboard().changeCount() as u64)
        }

        fn read(&self) -> Option<ClipItem> {
            autoreleasepool(|_| {
                let pb = NSPasteboard::generalPasteboard();
                if let Some(types) = pb.types() {
                    if types.iter().any(|t| SKIP.contains(&t.to_string().as_str())) {
                        return None;
                    }
                }
                let text = pb.stringForType(unsafe { NSPasteboardTypeString })?.to_string();
                (!text.is_empty() && text.len() <= MAX_TEXT).then_some(ClipItem::Text(text))
            })
        }

        fn write(&self, item: &ClipItem) -> Result<()> {
            let ClipItem::Text(text) = item;
            autoreleasepool(|_| {
                let pb = NSPasteboard::generalPasteboard();
                pb.clearContents();
                let ok = pb.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString });
                if ok { Ok(()) } else { bail!("pasteboard rejected the write") }
            })
        }
    }
}

